"""Transactional repositories; no external database implementation."""

from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum
from types import TracebackType
from typing import Protocol, Self

from richletsgo.domain import Environment, ExecutionEvent, OrderEvent, Qty, StrategyId, Symbol
from richletsgo.oms.models import OrderRecord, Transition
from richletsgo.portfolio.models import Action, CloseIntent, ProtectionRecovery, StrategyBook
from richletsgo.risk.records import DecisionRecord, EpisodeRecord


class FillStatus(StrEnum):
    BOOKED = "BOOKED"
    PENDING_ATTRIBUTION = "PENDING_ATTRIBUTION"
    EXTERNAL = "EXTERNAL"


@dataclass(frozen=True, slots=True)
class FillRecord:
    event: ExecutionEvent
    status: FillStatus
    order_key: str | None
    strategy: StrategyId | None


@dataclass(frozen=True, slots=True)
class LoggedOrderEvent:
    event: OrderEvent
    transition: Transition | None


class OrderRepository(Protocol):
    def get(self, key: str) -> OrderRecord | None: ...
    def find(
        self, order_link_id: str | None, exchange_order_id: str | None
    ) -> OrderRecord | None: ...
    def put(self, order: OrderRecord) -> None: ...
    def all(self) -> tuple[OrderRecord, ...]: ...


class FillRepository(Protocol):
    def get(self, exec_id: str) -> FillRecord | None: ...
    def add(self, fill: FillRecord) -> None: ...
    def replace(self, fill: FillRecord) -> None: ...
    def all(self) -> tuple[FillRecord, ...]: ...


class OrderEventLog(Protocol):
    def append(self, event: LoggedOrderEvent) -> None: ...
    def all(self) -> tuple[LoggedOrderEvent, ...]: ...


class PositionRepository(Protocol):
    """Quantity-only hook storage; strategy accounting is implemented in M1-04."""

    def get(self, strategy: StrategyId, symbol: Symbol) -> Qty: ...
    def set(self, strategy: StrategyId, symbol: Symbol, qty: Qty) -> None: ...
    def all(self) -> tuple[tuple[StrategyId, Symbol, Qty], ...]: ...


class DecisionRepository(Protocol):
    """One decision per signal_id within an account database (D60)."""

    def get(self, signal_id: str) -> DecisionRecord | None: ...
    def add(self, decision: DecisionRecord) -> None: ...
    def all(self) -> tuple[DecisionRecord, ...]: ...


class EpisodeRepository(Protocol):
    """At most one non-closed episode per (strategy, symbol) (D59)."""

    def get(self, episode_id: str) -> EpisodeRecord | None: ...
    def active_for(self, strategy: StrategyId, symbol: Symbol) -> EpisodeRecord | None: ...
    def put(self, episode: EpisodeRecord) -> None: ...
    def all(self) -> tuple[EpisodeRecord, ...]: ...


class PortfolioRepository(Protocol):
    def book(self, strategy: StrategyId, symbol: Symbol) -> StrategyBook: ...
    def put_book(self, book: StrategyBook) -> None: ...
    def books(self) -> tuple[StrategyBook, ...]: ...
    def intent(self, episode_id: str) -> CloseIntent | None: ...
    def put_intent(self, intent: CloseIntent) -> None: ...
    def intents(self) -> tuple[CloseIntent, ...]: ...
    def has_action(self, key: str) -> bool: ...
    def emit(self, action: Action) -> None: ...
    def actions(self) -> tuple[Action, ...]: ...
    def acknowledge(self, key: str) -> None: ...
    def paused(self, symbol: Symbol) -> bool: ...
    def pause(self, symbol: Symbol) -> None: ...
    def funding_seen(self, funding_id: str) -> bool: ...
    def mark_funding(self, funding_id: str) -> None: ...
    def stop_revision(self, symbol: Symbol) -> int: ...
    def next_stop_revision(self, symbol: Symbol, at: datetime) -> None: ...
    def stop_snapshot_at(self, symbol: Symbol) -> datetime | None: ...
    def last_fill_at(self, symbol: Symbol) -> datetime | None: ...
    def record_fill_at(self, symbol: Symbol, at: datetime) -> None: ...
    def pause_revision(self, symbol: Symbol) -> int: ...
    def clear_pause(self, symbol: Symbol) -> None: ...
    def recovery(self, strategy: StrategyId, symbol: Symbol) -> ProtectionRecovery | None: ...
    def put_recovery(
        self, strategy: StrategyId, symbol: Symbol, recovery: ProtectionRecovery | None
    ) -> None: ...


class RecoveryRepository(Protocol):
    """Account-scoped recovery and retained audit records in the same UoW.

    get/items include archives. active selects the exact first colon-delimited
    namespace (e.g. "trail:") through an index, without scanning audit records.
    archive preserves get and identical put replay must not reactivate it.
    """

    def get(self, key: str) -> str | None: ...
    def put(self, key: str, value: str) -> None: ...
    def items(self) -> tuple[tuple[str, str], ...]: ...
    def active(self, prefix: str) -> tuple[tuple[str, str], ...]: ...
    def archive(self, key: str) -> None: ...


class UnitOfWork(Protocol):
    recovery: RecoveryRepository
    environment: Environment
    portfolio: PortfolioRepository
    orders: OrderRepository
    fills: FillRepository
    order_events: OrderEventLog
    positions: PositionRepository
    decisions: DecisionRepository
    episodes: EpisodeRepository

    async def __aenter__(self) -> Self: ...
    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
